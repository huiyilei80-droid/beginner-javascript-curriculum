// Count how many times "Alex" appears in the list.
let names = ["michael", "jacob", "alex", "crystal", "oscar"];

let count = 0; 

for (let i = 0; i < names.length; i++) {
    if (names[i] === "alex") {
        count = count + 1;
    }
}

console.log(count); 

